export function generateModuleQuestions(
  subjectId: string,
  subjectCode: string,
  subjectName: string,
  moduleNumber: 1 | 2 | 3 | 4 | 5,
  count: number,
  difficulty: DifficultyLevel
): MCQQuestion[] {
  const topics = TOPIC_MAP[subjectCode]?.[moduleNumber] || [
    'Core Principles',
    'Analytical Formulation',
    'System Verification',
    'Design Optimization',
    'Operational Standards',
    'Performance Evaluation',
  ];
  const options: ('A' | 'B' | 'C' | 'D')[] = ['A', 'B', 'C', 'D'];
  const list: MCQQuestion[] = [];

  for (let i = 1; i <= count; i++) {
    const topic = topics[(i - 1) % topics.length];
    const qNum = String(i).padStart(3, '0');
    const questionId = `QB-${subjectCode}-M${moduleNumber}-${qNum}`;
    const correctOption = options[(i + moduleNumber) % 4];

    list.push({
      questionId,
      subjectId,
      moduleNumber,
      questionText: `[${subjectCode} · Module ${moduleNumber} · Item #${i}] In ${subjectName}, which technical condition governs ${topic} under deterministic operational constraints (Variant ${moduleNumber}.${i})?`,
      optionA: `Enforce strict invariant verification across ${topic} boundaries (Parameter Set α-${i})`,
      optionB: `Apply bounded state transition normalization for ${topic} (Parameter Set β-${i})`,
      optionC: `Execute decoupled pipeline partitioning with checksum validation for ${topic} (Parameter Set γ-${i})`,
      optionD: `Maintain constant-time lookup tables without feedback calibration for ${topic} (Parameter Set δ-${i})`,
      correctOption,
      difficulty,
      updatedAt: '2026-11-08T10:30:00Z',
    });
  }

  return list;
}

