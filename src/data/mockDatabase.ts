function generateStudentsForSection(
  deptId: string,
  deptCode: string,
  usnBranch: string,
  semId: string,
  semNumber: number,
  section: string,
  offset: number,
  count: number
): StudentRecord[] {
  const list: StudentRecord[] = [];
  for (let i = 1; i <= count; i++) {
    const seq = String(offset + i).padStart(3, '0');
    const usn = `4MH24${usnBranch}${seq}`;
    const name = `${CSE_STUDENT_NAMES[(i - 1) % CSE_STUDENT_NAMES.length]}${i > CSE_STUDENT_NAMES.length ? ' II' : ''}`;
    const month = String(((i % 12) + 1)).padStart(2, '0');
    const day = String(((i % 27) + 1)).padStart(2, '0');
    list.push({
      id: `stu-${deptCode.toLowerCase()}-${section.replace(/\s+/g, '').toLowerCase()}-${seq}`,
      usn,
      studentName: name,
      dob: `2006-${month}-${day}`,
      departmentId: deptId,
      departmentCode: deptCode,
      semesterId: semId,
      semesterNumber: semNumber,
      section,
      academicYearId: 'ay-2026-27',
      isValid: true,
      validationErrors: [],
    });
  }
  return list;
}

